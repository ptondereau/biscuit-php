<?php

declare(strict_types=1);

namespace Biscuit\BiscuitBundle\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

final class Configuration implements ConfigurationInterface
{
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('biscuit');

        $treeBuilder->getRootNode()
            ->children()
                ->arrayNode('keys')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('public_key')
                            ->defaultNull()
                            ->info('Public key in hexadecimal format')
                        ->end()
                        ->scalarNode('private_key')
                            ->defaultNull()
                            ->info('Private key in hexadecimal format')
                        ->end()
                        ->scalarNode('public_key_file')
                            ->defaultNull()
                            ->info('Path to public key file')
                        ->end()
                        ->scalarNode('private_key_file')
                            ->defaultNull()
                            ->info('Path to private key file')
                        ->end()
                        ->enumNode('algorithm')
                            ->values(['ed25519', 'secp256r1'])
                            ->defaultValue('ed25519')
                            ->info('Cryptographic algorithm for key generation')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('security')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('user_identifier_fact')
                            ->defaultValue('user')
                            ->cannotBeEmpty()
                            ->info('Authority block fact carrying the user identifier, e.g. user("alice")')
                        ->end()
                        ->booleanNode('www_authenticate')
                            ->defaultTrue()
                            ->info('Send an RFC 6750 WWW-Authenticate challenge on authentication failure')
                        ->end()
                        ->scalarNode('realm')
                            ->defaultValue('api')
                            ->cannotBeEmpty()
                            ->info('Realm advertised in the WWW-Authenticate challenge')
                        ->end()
                        ->arrayNode('token_extractor')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('header')
                                    ->defaultTrue()
                                    ->info('Extract token from Authorization header')
                                ->end()
                                ->scalarNode('cookie')
                                    ->defaultFalse()
                                    ->info('Cookie name to extract token from, or false to disable')
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('revocation')
                    ->addDefaultsIfNotSet()
                    ->info('Revocation list checking. A token is revoked when ANY of its revocation ids is listed, so revoking a parent id also revokes every token attenuated from it.')
                    ->children()
                        ->booleanNode('enabled')
                            ->defaultFalse()
                            ->info('Enable token revocation checking')
                        ->end()
                        ->enumNode('on_unavailable')
                            ->values(['allow', 'deny'])
                            ->defaultNull()
                            ->info('Required when enabled. What to do when a store cannot answer: "deny" rejects the request (fail closed), "allow" accepts it and logs an error (fail open).')
                        ->end()
                        ->enumNode('dispatch_check_events')
                            ->values(['never', 'on_revoke', 'always'])
                            ->defaultValue('on_revoke')
                            ->info('When to dispatch BiscuitRevocationCheckedEvent. Checks run on every authenticated request, so "always" is opt-in.')
                        ->end()
                        ->integerNode('default_expiry')
                            ->defaultNull()
                            ->min(1)
                            ->info('Seconds to keep an entry whose expiration is unknown. Null keeps it forever, which is deliberate: an entry expiring before its token does silently un-revokes the token.')
                        ->end()
                        ->arrayNode('stores')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->arrayNode('static')
                                    ->addDefaultsIfNotSet()
                                    ->info('Immutable break-glass list. No I/O on the request path, checked first.')
                                    ->children()
                                        ->variableNode('ids')
                                            ->defaultValue([])
                                            ->info('Revoked ids (lowercase hex), or an env placeholder resolving to a list, e.g. "%env(csv:BISCUIT_REVOKED_IDS)%"')
                                        ->end()
                                        ->scalarNode('file')
                                            ->defaultNull()
                                            ->info('Path to a newline-delimited or JSON list of revoked ids, read lazily')
                                        ->end()
                                    ->end()
                                ->end()
                                ->arrayNode('cache')
                                    ->canBeEnabled()
                                    ->info('PSR-6 backed list. Point it at a shared pool such as Redis and every instance converges.')
                                    ->children()
                                        ->scalarNode('pool')
                                            ->defaultNull()
                                            ->info('Existing cache pool service id. Null creates a dedicated cache.biscuit.revocation pool.')
                                        ->end()
                                        ->scalarNode('adapter')
                                            ->defaultValue('cache.app')
                                            ->cannotBeEmpty()
                                            ->info('Parent adapter used when creating the dedicated pool')
                                        ->end()
                                        ->scalarNode('key_prefix')
                                            ->defaultValue('biscuit_revoked_')
                                            ->cannotBeEmpty()
                                            ->info('Cache key prefix, to isolate several applications sharing one pool')
                                        ->end()
                                    ->end()
                                ->end()
                                ->arrayNode('in_memory')
                                    ->canBeEnabled()
                                    ->info('In-process list. Useful in tests and in worker runtimes fed over a transport.')
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('push')
                            ->canBeEnabled()
                            ->info('Broadcast every write over Symfony Messenger so instances holding in-process lists learn immediately. Route the messages to a fanout transport: a work queue delivers each message to exactly one instance, leaving every other node accepting the token.')
                            ->children()
                                ->scalarNode('bus')
                                    ->defaultValue('messenger.default_bus')
                                    ->cannotBeEmpty()
                                    ->info('Message bus service id used to dispatch and to register the handlers')
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('policies')
                    ->useAttributeAsKey('name')
                    ->scalarPrototype()->end()
                    ->info('Named policy strings for authorization')
                ->end()
                ->arrayNode('token_templates')
                    ->useAttributeAsKey('name')
                    ->arrayPrototype()
                        ->children()
                            ->arrayNode('facts')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog facts for the token')
                            ->end()
                            ->arrayNode('checks')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog checks for the token')
                            ->end()
                            ->arrayNode('rules')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog rules for the token')
                            ->end()
                        ->end()
                    ->end()
                    ->info('Token templates with facts, checks, and rules')
                ->end()
                ->arrayNode('block_templates')
                    ->useAttributeAsKey('name')
                    ->arrayPrototype()
                        ->children()
                            ->arrayNode('facts')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog facts for the attenuation block')
                            ->end()
                            ->arrayNode('checks')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog checks for the attenuation block')
                            ->end()
                            ->arrayNode('rules')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog rules for the attenuation block')
                            ->end()
                        ->end()
                    ->end()
                    ->info('Block templates applied during token attenuation')
                ->end()
                ->arrayNode('authorizer_fact_templates')
                    ->useAttributeAsKey('name')
                    ->arrayPrototype()
                        ->children()
                            ->arrayNode('facts')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog facts injected into the authorizer when the matching policy is evaluated')
                            ->end()
                            ->arrayNode('checks')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog checks injected into the authorizer when the matching policy is evaluated')
                            ->end()
                            ->arrayNode('rules')
                                ->scalarPrototype()->end()
                                ->defaultValue([])
                                ->info('Datalog rules injected into the authorizer when the matching policy is evaluated')
                            ->end()
                        ->end()
                    ->end()
                    ->info('Authorizer fact templates applied by policy name before authorization')
                ->end()
            ->end()
        ;

        return $treeBuilder;
    }
}
